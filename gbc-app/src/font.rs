pub fn draw_text(
    frame: &mut [u8],
    stride_pixels: usize,
    start_x: usize,
    start_y: usize,
    text: &str,
    color: [u8; 4],
    scale: usize,
) {
    let scale = scale.max(1);
    let mut cur_x = start_x;

    for ch in text.chars() {
        let g = glyph(ch);
        for (row_idx, &row_byte) in g.iter().enumerate() {
            for col_idx in 0..8 {
                if (row_byte & (1 << (7 - col_idx))) != 0 {
                    for sy in 0..scale {
                        for sx in 0..scale {
                            let px = cur_x + col_idx * scale + sx;
                            let py = start_y + row_idx * scale + sy;
                            let idx = (py * stride_pixels + px) * 4;
                            if idx + 4 <= frame.len() {
                                frame[idx..idx + 4].copy_from_slice(&color);
                            }
                        }
                    }
                }
            }
        }
        cur_x += 8 * scale;
    }
}
